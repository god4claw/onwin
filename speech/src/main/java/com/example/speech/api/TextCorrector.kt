package com.example.speech.api

/**
 * Постобработка текста распознавания: правка ослышек и опечаток в словах.
 *
 * Контракт намеренно узкий — корректор меняет только [com.example.speech.api.Segment.text]
 * и не имеет права трогать спикеров и метки времени: их считает диаризация, и
 * пересчёт в `Done` их всё равно перезапишет.
 *
 * Реализации обязаны быть безопасными к плохому ответу: любая правка, которая
 * слишком далеко ушла от исходного текста, должна откатываться к нему самому.
 * Исходный текст всегда валиден — это выход ASR, а не черновик.
 */
interface TextCorrector {
    /** Готовит ресурсы (модель, словарь). Вызывать один раз перед работой. */
    suspend fun load()

    /** Возвращает исправленный текст или [text] без изменений. */
    suspend fun correct(text: String): String

    /** Освобождает ресурсы. */
    fun release()
}

/**
 * Генератор текста — точка подключения конкретного LLM-рантайма
 * (llama.cpp через JNI, MediaPipe GenAI и т. п.).
 *
 * Модуль `:speech` не тянет нативный рантайм сам: он весит десятки мегабайт и
 * собирается под каждый ABI отдельно. Приложение подставляет реализацию, а вся
 * логика правки, гардов и масок живёт здесь и проверяется JVM-тестами с
 * поддельным генератором.
 */
interface TextGenerator {
    /** Загружает веса. */
    suspend fun load()

    /**
     * Возвращает продолжение по [prompt], не длиннее [maxTokens].
     *
     * Реализация должна уметь прерваться, когда корутина отменена: иначе
     * `withTimeoutOrNull` вокруг вызова не остановит нативный токен-цикл, и
     * генерация продолжит занимать ядра.
     */
    suspend fun generate(prompt: String, maxTokens: Int): String

    /** Освобождает веса. */
    fun release()
}
